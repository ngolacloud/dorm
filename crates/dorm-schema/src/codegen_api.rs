//! Generate a CRUD API: an Axum service over the models, with an embedded
//! OpenAPI document. The generated binary serves, per model, `GET`/`POST
//! /<table>` and `GET`/`PATCH`/`DELETE /<table>/{id}` as JSON, plus
//! `GET /openapi.json` and `/health`.
//!
//! The generated code stays in the ORM context: handlers go through the same
//! `QuerySet` and compiler, so the schema, the rules and the performance are
//! shared. The write body is a dynamic JSON object today; typed request schemas
//! are on the roadmap.

use std::fmt::Write as _;

use serde_json::{json, Map, Value as J};

use crate::{snake, Field, Model, Scalar, Schema};

/// Render `src/bin/api.rs` for a schema. `krate` is the project's library crate
/// name (underscored), which the binary imports its models from.
pub fn generate_axum(schema: &Schema, krate: &str) -> String {
    let model_names: Vec<&str> = schema.models.iter().map(|m| m.name.as_str()).collect();

    let mut out = String::new();
    out.push_str(HEADER);
    out.push('\n');
    out.push_str(&imports(krate, &model_names));
    out.push('\n');
    out.push_str(PREAMBLE);
    out.push('\n');

    // Per-model handlers.
    for m in &schema.models {
        out.push_str(&handlers(m));
        out.push('\n');
    }

    // The embedded OpenAPI document.
    let doc = serde_json::to_string_pretty(&openapi(schema)).unwrap_or_else(|_| "{}".into());
    out.push_str("/// The OpenAPI 3 document describing this API.\n");
    // `r##"…"##`: the document contains `"#/components/…"` ($ref), so the inner
    // `"#` would close a plain `r#"…"#`.
    let _ = writeln!(out, "const OPENAPI_JSON: &str = r##\"{doc}\"##;\n");

    out.push_str(&main_fn(schema));
    out
}

const HEADER: &str =
    "// @generated by `dorm api generate` from dorm.schema — do not edit by hand.\n\
     // A CRUD API over the models, with OpenAPI at /openapi.json. Edit dorm.schema\n\
     // and re-run `dorm api generate`. Run with `dorm api serve` (DORM_API_ADDR).\n";

fn imports(krate: &str, models: &[&str]) -> String {
    let mut out = String::new();
    out.push_str("use axum::extract::{Path, Query};\n");
    out.push_str("use axum::http::StatusCode;\n");
    out.push_str("use axum::routing::get;\n");
    out.push_str("use axum::{Json, Router};\n");
    // Specific imports, never `prelude::*`: the prelude's one-argument `Result`
    // would shadow `std::result::Result` in the handler signatures.
    out.push_str("use dorm_core::compiler;\n");
    out.push_str("use dorm_core::expr::{Assignment, F};\n");
    out.push_str("use dorm_core::model::Model;\n");
    out.push_str("use dorm_core::queryset::ValueRow;\n");
    out.push_str("use dorm_core::value::Value;\n");
    let _ = writeln!(out, "use {krate}::models::{{{}}};", models.join(", "));
    out
}

const PREAMBLE: &str = r#"#[derive(serde::Deserialize)]
struct ListParams {
    limit: Option<i64>,
    offset: Option<i64>,
}

type ApiError = (StatusCode, String);

fn err(e: impl std::fmt::Display) -> ApiError {
    (StatusCode::INTERNAL_SERVER_ERROR, e.to_string())
}

/// Each ORM `Value` as plain JSON — numbers as numbers, everything temporal or
/// exact as a string so nothing is silently lossy.
fn value_to_json(v: &Value) -> serde_json::Value {
    match v {
        Value::Null => serde_json::Value::Null,
        Value::Bool(b) => serde_json::Value::Bool(*b),
        Value::I32(n) => serde_json::Value::from(*n),
        Value::I64(n) => serde_json::Value::from(*n),
        Value::Text(s) => serde_json::Value::String(s.clone()),
        Value::Decimal(d) => serde_json::Value::String(d.to_string()),
        Value::Timestamp(t) => serde_json::Value::String(t.to_rfc3339()),
        Value::Uuid(u) => serde_json::Value::String(u.to_string()),
        Value::Json(j) => j.clone(),
    }
}

fn row_to_json(row: &ValueRow) -> serde_json::Value {
    serde_json::Value::Object(
        row.iter()
            .map(|(k, v)| (k.clone(), value_to_json(v)))
            .collect(),
    )
}

/// A path id parsed as an integer when it looks like one, else kept as text —
/// so both serial and natural (text) keys work.
fn id_value(raw: &str) -> Value {
    match raw.parse::<i64>() {
        Ok(n) => Value::I64(n),
        Err(_) => Value::Text(raw.to_string()),
    }
}

/// A JSON body value as an ORM `Value`. The compiler coerces it to the column's
/// declared type, so a JSON number reaching a `Decimal` column, or an RFC-3339
/// string reaching a timestamp, both land correctly. Non-integer numbers travel
/// as text so no precision is lost on the way to `Decimal`.
fn json_to_value(v: &serde_json::Value) -> Value {
    match v {
        serde_json::Value::Null => Value::Null,
        serde_json::Value::Bool(b) => Value::Bool(*b),
        serde_json::Value::Number(n) => match n.as_i64() {
            Some(i) => Value::I64(i),
            None => Value::Text(n.to_string()),
        },
        serde_json::Value::String(s) => Value::Text(s.clone()),
        other => Value::Json(other.clone()),
    }
}

type Body = serde_json::Map<String, serde_json::Value>;

async fn openapi() -> ([(axum::http::HeaderName, &'static str); 1], &'static str) {
    (
        [(axum::http::header::CONTENT_TYPE, "application/json")],
        OPENAPI_JSON,
    )
}
"#;

fn handlers(m: &Model) -> String {
    let lower = snake(&m.name);
    let mut out = String::new();

    // List.
    let _ = writeln!(
        out,
        "async fn list_{lower}(Query(p): Query<ListParams>) \
         -> Result<Json<serde_json::Value>, ApiError> {{"
    );
    let _ = writeln!(
        out,
        "    let rows = {name}::objects().limit(p.limit.unwrap_or(50)).offset(p.offset.unwrap_or(0)).rows().await.map_err(err)?;",
        name = m.name
    );
    out.push_str(
        "    Ok(Json(serde_json::Value::Array(rows.iter().map(row_to_json).collect())))\n",
    );
    out.push_str("}\n");

    // Create: insert the body's columns, return the stored row (so generated
    // and default columns come back). Dynamic — the body is a JSON object.
    let _ = writeln!(
        out,
        "\nasync fn create_{lower}(Json(body): Json<Body>) \
         -> Result<(StatusCode, Json<serde_json::Value>), ApiError> {{"
    );
    out.push_str(
        "    let values: Vec<(String, Value)> = body.iter().map(|(k, v)| (k.clone(), json_to_value(v))).collect();\n",
    );
    let _ = writeln!(
        out,
        "    let sql = compiler::compile_insert({name}::meta(), std::slice::from_ref(&values)).map_err(err)?;",
        name = m.name
    );
    out.push_str("    let rows = dorm_core::model::run_query(&sql).await.map_err(err)?;\n");
    out.push_str("    let row = rows.first().ok_or((StatusCode::INTERNAL_SERVER_ERROR, \"insert returned no row\".to_string()))?;\n");
    out.push_str("    let mut map = ValueRow::new();\n");
    out.push_str("    for (i, spec) in sql.columns.iter().enumerate() {\n");
    out.push_str("        map.insert(spec.name.clone(), dorm_core::value::read_column(row, i, spec.ty, &spec.name).map_err(err)?);\n");
    out.push_str("    }\n");
    out.push_str("    Ok((StatusCode::CREATED, Json(row_to_json(&map))))\n");
    out.push_str("}\n");

    // Fetch / update / delete by primary key, when there is one.
    if let Some(pk) = m.primary_key() {
        let col = &pk.column;
        let _ = writeln!(
            out,
            "\nasync fn get_{lower}(Path(id): Path<String>) \
             -> Result<Json<serde_json::Value>, ApiError> {{"
        );
        let _ = writeln!(
            out,
            "    let rows = {name}::objects().filter_str(\"{col}\", id_value(&id)).limit(1).rows().await.map_err(err)?;",
            name = m.name
        );
        out.push_str("    match rows.first() {\n");
        out.push_str("        Some(row) => Ok(Json(row_to_json(row))),\n");
        out.push_str("        None => Err((StatusCode::NOT_FOUND, \"not found\".into())),\n");
        out.push_str("    }\n");
        out.push_str("}\n");

        // Update: set the body's columns on the row with this id, return it.
        let _ = writeln!(
            out,
            "\nasync fn update_{lower}(Path(id): Path<String>, Json(body): Json<Body>) \
             -> Result<Json<serde_json::Value>, ApiError> {{"
        );
        out.push_str("    let assignments: Vec<Assignment> = body.iter().map(|(k, v)| Assignment::new(k.clone(), F::lit(json_to_value(v)))).collect();\n");
        out.push_str("    if assignments.is_empty() {\n        return Err((StatusCode::BAD_REQUEST, \"empty body\".into()));\n    }\n");
        let _ = writeln!(
            out,
            "    let n = {name}::objects().filter_str(\"{col}\", id_value(&id)).update(assignments).await.map_err(err)?;",
            name = m.name
        );
        out.push_str("    if n == 0 {\n        return Err((StatusCode::NOT_FOUND, \"not found\".into()));\n    }\n");
        let _ = writeln!(
            out,
            "    let rows = {name}::objects().filter_str(\"{col}\", id_value(&id)).limit(1).rows().await.map_err(err)?;",
            name = m.name
        );
        out.push_str("    match rows.first() {\n        Some(row) => Ok(Json(row_to_json(row))),\n        None => Err((StatusCode::NOT_FOUND, \"not found\".into())),\n    }\n");
        out.push_str("}\n");

        // Delete: remove the row with this id.
        let _ = writeln!(
            out,
            "\nasync fn delete_{lower}(Path(id): Path<String>) -> Result<StatusCode, ApiError> {{"
        );
        let _ = writeln!(
            out,
            "    let n = {name}::objects().filter_str(\"{col}\", id_value(&id)).delete().await.map_err(err)?;",
            name = m.name
        );
        out.push_str("    if n == 0 {\n        Err((StatusCode::NOT_FOUND, \"not found\".into()))\n    } else {\n        Ok(StatusCode::NO_CONTENT)\n    }\n");
        out.push_str("}\n");
    }
    out
}

fn main_fn(schema: &Schema) -> String {
    let mut routes = String::new();
    for m in &schema.models {
        let lower = snake(&m.name);
        let table = &m.table;
        let _ = writeln!(
            routes,
            "        .route(\"/{table}\", get(list_{lower}).post(create_{lower}))"
        );
        if m.primary_key().is_some() {
            let _ = writeln!(
                routes,
                "        .route(\"/{table}/:id\", get(get_{lower}).patch(update_{lower}).delete(delete_{lower}))"
            );
        }
    }

    format!(
        r#"#[tokio::main]
async fn main() {{
    let app = Router::new()
        .route("/health", get(|| async {{ "ok" }}))
        .route("/openapi.json", get(openapi))
{routes}        ;
    // Override the listen address with DORM_API_ADDR (host:port).
    let addr = std::env::var("DORM_API_ADDR").unwrap_or_else(|_| "127.0.0.1:8080".to_string());
    let listener = tokio::net::TcpListener::bind(&addr)
        .await
        .unwrap_or_else(|e| panic!("bind {{addr}}: {{e}}"));
    let bound = listener.local_addr().map(|a| a.to_string()).unwrap_or(addr);
    println!("dorm api on http://{{bound}} — OpenAPI at http://{{bound}}/openapi.json");
    axum::serve(listener, app).await.expect("serve");
}}
"#
    )
}

/// Build the OpenAPI 3 document for the schema.
fn openapi(schema: &Schema) -> J {
    let mut paths = Map::new();
    let mut schemas = Map::new();
    for m in &schema.models {
        let body = json!({
            "required": true,
            "content": { "application/json": {
                "schema": { "$ref": format!("#/components/schemas/{}", m.name) }
            } }
        });
        let list = json!({
            "get": {
                "summary": format!("List {}", m.name),
                "parameters": [
                    { "name": "limit", "in": "query", "schema": { "type": "integer" } },
                    { "name": "offset", "in": "query", "schema": { "type": "integer" } }
                ],
                "responses": { "200": { "description": format!("a page of {}", m.name) } }
            },
            "post": {
                "summary": format!("Create a {}", m.name),
                "requestBody": body.clone(),
                "responses": { "201": { "description": m.name } }
            }
        });
        paths.insert(format!("/{}", m.table), list);

        if m.primary_key().is_some() {
            let id_param = json!([
                { "name": "id", "in": "path", "required": true, "schema": { "type": "string" } }
            ]);
            let item = json!({
                "get": {
                    "summary": format!("Fetch one {} by id", m.name),
                    "parameters": id_param.clone(),
                    "responses": { "200": { "description": m.name }, "404": { "description": "not found" } }
                },
                "patch": {
                    "summary": format!("Update a {} by id", m.name),
                    "parameters": id_param.clone(),
                    "requestBody": body,
                    "responses": { "200": { "description": m.name }, "404": { "description": "not found" } }
                },
                "delete": {
                    "summary": format!("Delete a {} by id", m.name),
                    "parameters": id_param,
                    "responses": { "204": { "description": "deleted" }, "404": { "description": "not found" } }
                }
            });
            paths.insert(format!("/{}/{{id}}", m.table), item);
        }

        schemas.insert(m.name.clone(), component_schema(m));
    }

    json!({
        "openapi": "3.0.3",
        "info": { "title": "DORM API", "version": "0.1.0" },
        "paths": J::Object(paths),
        "components": { "schemas": J::Object(schemas) }
    })
}

fn component_schema(m: &Model) -> J {
    let mut props = Map::new();
    for f in &m.fields {
        match f {
            Field::Scalar(s) => {
                props.insert(s.column.clone(), openapi_scalar(s.ty, s.nullable));
            }
            Field::ToOne(r) => {
                // The foreign key is exposed as its integer id column.
                props.insert(r.column.clone(), json!({ "type": "integer" }));
            }
            Field::ToMany { .. } => {}
        }
    }
    json!({ "type": "object", "properties": J::Object(props) })
}

fn openapi_scalar(ty: Scalar, nullable: bool) -> J {
    let (t, fmt) = match ty {
        Scalar::Int | Scalar::BigInt => ("integer", None),
        Scalar::String => ("string", None),
        Scalar::Boolean => ("boolean", None),
        Scalar::DateTime => ("string", Some("date-time")),
        Scalar::Decimal => ("string", None),
        Scalar::Json => ("object", None),
        Scalar::Uuid => ("string", Some("uuid")),
    };
    let mut obj = Map::new();
    obj.insert("type".into(), J::String(t.into()));
    if let Some(f) = fmt {
        obj.insert("format".into(), J::String(f.into()));
    }
    if nullable {
        obj.insert("nullable".into(), J::Bool(true));
    }
    J::Object(obj)
}

#[cfg(test)]
mod tests {
    use crate::{generate_axum, parse};

    #[test]
    fn generates_axum_routes_and_openapi() {
        let schema = parse(
            r#"
            model Tenant {
              id   Int    @id @default(autoincrement())
              slug String @db.VarChar(63)
            }
        "#,
        )
        .expect("parses");
        let rust = generate_axum(&schema, "demo_app");
        assert!(rust.contains("use demo_app::models::{Tenant};"));
        assert!(rust.contains("async fn list_tenant("));
        assert!(rust.contains("async fn get_tenant("));
        assert!(rust.contains("async fn create_tenant("));
        assert!(rust.contains("async fn update_tenant("));
        assert!(rust.contains("async fn delete_tenant("));
        assert!(rust.contains(".route(\"/tenants\", get(list_tenant).post(create_tenant))"));
        assert!(rust.contains(
            ".route(\"/tenants/:id\", get(get_tenant).patch(update_tenant).delete(delete_tenant))"
        ));
        assert!(rust.contains("\"openapi\": \"3.0.3\""));
        assert!(rust.contains("Tenant::objects()"));
    }
}
