//! Monthly range partitioning + retention against a real PostgreSQL (ADR 0029 / L10).
//!
//! ```text
//! DELONIX_ORM_TEST_DSN='host=127.0.0.1 port=5432 user=orm dbname=ormtest' \
//!   cargo test -p dorm-models --test partitions_live -- --ignored --nocapture
//! ```

use dorm_core::db;
use dorm_core::value::Value;
use dorm_migrations::partition;
use tokio::runtime::Runtime;

fn dsn() -> Option<String> {
    std::env::var("DELONIX_ORM_TEST_DSN")
        .ok()
        .filter(|s| !s.trim().is_empty())
}

fn runtime() -> &'static Runtime {
    static RT: std::sync::OnceLock<Runtime> = std::sync::OnceLock::new();
    RT.get_or_init(|| {
        tokio::runtime::Builder::new_multi_thread()
            .worker_threads(2)
            .enable_all()
            .build()
            .expect("a tokio runtime")
    })
}

async fn count_where(note: &str) -> i64 {
    db::sql(
        "SELECT COUNT(*)::bigint FROM l10_events WHERE note = $1",
        &[Value::Text(note.to_string())],
    )
    .await
    .unwrap()[0]
        .try_get::<i64>(0)
        .unwrap()
}

async fn partition_exists(name: &str) -> bool {
    !db::sql(
        "SELECT 1 FROM pg_class WHERE relname = $1",
        &[Value::Text(name.to_string())],
    )
    .await
    .unwrap()
    .is_empty()
}

#[test]
#[ignore = "needs a Postgres (DELONIX_ORM_TEST_DSN)"]
fn partitions_are_created_ahead_rows_route_and_old_months_are_retained_out() {
    let Some(dsn) = dsn() else {
        eprintln!("skipped: DELONIX_ORM_TEST_DSN is not set");
        return;
    };
    std::env::set_var(dorm_core::db::DSN_ENV, &dsn);

    runtime().block_on(async {
        db::execute("DROP TABLE IF EXISTS l10_events CASCADE", &[])
            .await
            .expect("clean");

        // A range-partitioned append-only table.
        let ddl = partition::create_parent_ddl(
            "l10_events",
            "id BIGINT GENERATED BY DEFAULT AS IDENTITY, at TIMESTAMPTZ NOT NULL, \
             note TEXT NOT NULL, PRIMARY KEY (id, at)",
            "at",
        )
        .unwrap();
        db::execute(&ddl, &[]).await.expect("parent");

        // Partitions for this month and next — ahead of the rows that need them.
        let made = partition::ensure_month_partitions("l10_events", 1)
            .await
            .expect("ensure");
        assert!(made >= 2, "this month and next were ensured (got {made})");

        // A row at `now()` routes into the current partition and reads back.
        db::execute(
            "INSERT INTO l10_events (at, note) VALUES (now(), 'now-row')",
            &[],
        )
        .await
        .expect("insert now");
        assert_eq!(count_where("now-row").await, 1, "the current row is stored");

        // An old partition with an old row, well past any retention window.
        db::execute(
            "CREATE TABLE IF NOT EXISTS l10_events_201901 PARTITION OF l10_events \
             FOR VALUES FROM ('2019-01-01') TO ('2019-02-01')",
            &[],
        )
        .await
        .expect("old partition");
        db::execute(
            "INSERT INTO l10_events (at, note) VALUES ('2019-01-15', 'old-row')",
            &[],
        )
        .await
        .expect("insert old");
        assert_eq!(count_where("old-row").await, 1);
        assert!(partition_exists("l10_events_201901").await);

        // Retention: drop everything older than 24 months. The 2019 month goes;
        // the current one stays.
        let dropped = partition::drop_partitions_older_than("l10_events", 24)
            .await
            .expect("retention");
        assert!(
            dropped.contains(&"l10_events_201901".to_string()),
            "the old month was detached and dropped: {dropped:?}"
        );
        assert!(
            !partition_exists("l10_events_201901").await,
            "the old partition is gone"
        );
        assert_eq!(count_where("old-row").await, 0, "its rows went with it");
        assert_eq!(
            count_where("now-row").await,
            1,
            "the current month is untouched"
        );
    });
}
