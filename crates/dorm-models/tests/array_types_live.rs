//! Array columns (`TEXT[]`/`BIGINT[]`) + set lookups against PostgreSQL (ADR 0041).
//!
//! ```text
//! DELONIX_ORM_TEST_DSN='host=127.0.0.1 port=5432 user=orm dbname=ormtest' \
//!   cargo test -p dorm-models --test array_types_live -- --ignored --nocapture
//! ```

use dorm_core::compiler::{compile_select, Plan};
use dorm_core::expr::Q;
use dorm_core::model::Model;
use dorm_core::prelude::*;
use dorm_derive::Model;
use tokio::runtime::Runtime;

/// A document with a text-array `tags` column — the common control-plane shape.
#[derive(Model, Debug, Clone)]
#[model(table = "l5_tagged", ordering = "id")]
struct Tagged {
    #[field(primary_key)]
    id: i64,
    #[field(column_type = "text[]")]
    tags: Vec<String>,
}

fn dsn() -> Option<String> {
    std::env::var("DELONIX_ORM_TEST_DSN")
        .ok()
        .filter(|s| !s.trim().is_empty())
}

fn runtime() -> &'static Runtime {
    static RT: std::sync::OnceLock<Runtime> = std::sync::OnceLock::new();
    RT.get_or_init(|| {
        tokio::runtime::Builder::new_multi_thread()
            .worker_threads(2)
            .enable_all()
            .build()
            .expect("a tokio runtime")
    })
}

/// Pure SQL-shape: `array_contains` emits `@>` and binds the array as one param.
#[test]
fn an_array_lookup_emits_the_operator_and_binds_one_array() {
    let mut plan = Plan::new(Tagged::meta());
    plan.filters.push(Q::new(
        "tags__array_contains",
        vec!["rust".to_string(), "db".to_string()],
    ));
    let sql = compile_select(&plan).expect("compiles");
    assert!(sql.text.contains("@>"), "contains operator: {}", sql.text);
    assert_eq!(
        sql.params[0],
        Value::TextArray(vec!["rust".into(), "db".into()]),
        "the array binds as one parameter"
    );
    assert_eq!(FieldType::TextArray.sql_type(), "TEXT[]");
}

#[test]
#[ignore = "needs a Postgres (DELONIX_ORM_TEST_DSN)"]
fn array_columns_round_trip_and_set_lookups_find_the_right_rows() {
    let Some(dsn) = dsn() else {
        eprintln!("skipped: DELONIX_ORM_TEST_DSN is not set");
        return;
    };
    std::env::set_var(dorm_core::db::DSN_ENV, &dsn);

    runtime().block_on(async {
        dorm_core::db::execute("DROP TABLE IF EXISTS l5_tagged", &[])
            .await
            .expect("clean");
        dorm_core::db::execute(
            "CREATE TABLE l5_tagged (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tags TEXT[] NOT NULL)",
            &[],
        )
        .await
        .expect("table");

        let rows = [
            vec!["rust", "db", "orm"],
            vec!["rust", "web"],
            vec!["python", "db"],
        ];
        for tags in rows {
            Tagged::objects()
                .create(NewTagged {
                    tags: tags.iter().map(|s| s.to_string()).collect(),
                })
                .await
                .expect("insert");
        }

        // Round-trip: the array reads back as the Vec<String> it was stored as.
        let first = Tagged::objects()
            .order_by_str(&["id"])
            .first()
            .await
            .expect("query")
            .expect("a row");
        assert_eq!(first.tags, vec!["rust", "db", "orm"]);

        // contains (@>): rows whose tags include *all* of {rust, db}.
        let has_both = Tagged::objects()
            .filter_str(
                "tags__array_contains",
                vec!["rust".to_string(), "db".to_string()],
            )
            .count()
            .await
            .expect("array_contains");
        assert_eq!(has_both, 1, "only the first row has both rust and db");

        // overlap (&&): rows sharing *any* tag with {python, orm}.
        let overlaps = Tagged::objects()
            .filter_str(
                "tags__array_overlap",
                vec!["python".to_string(), "orm".to_string()],
            )
            .count()
            .await
            .expect("array_overlap");
        assert_eq!(overlaps, 2, "row 1 (orm) and row 3 (python)");

        // contained_by (<@): rows all of whose tags are within a superset.
        let within = Tagged::objects()
            .filter_str(
                "tags__array_contained_by",
                vec![
                    "rust".to_string(),
                    "web".to_string(),
                    "extra".to_string(),
                ],
            )
            .count()
            .await
            .expect("array_contained_by");
        assert_eq!(within, 1, "only the rust/web row is within rust/web/extra");

        // An array lookup on a non-array column is refused before any SQL runs.
        let err = Tagged::objects()
            .filter_str("id__array_contains", vec!["x".to_string()])
            .count()
            .await
            .expect_err("array lookup on a bigint column must be refused");
        assert!(err.to_string().contains("array"), "got {err:?}");
    });
}
