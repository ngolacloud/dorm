//! Soft delete + purge against a real PostgreSQL (ADR 0033 / L14).
//!
//! ```text
//! DELONIX_ORM_TEST_DSN='host=127.0.0.1 port=5432 user=orm dbname=ormtest' \
//!   cargo test -p dorm-models --test soft_delete_live -- --ignored --nocapture
//! ```

use chrono::{DateTime, Utc};
use dorm_core::model::Model;
use dorm_core::prelude::*;
use dorm_derive::Model;
use tokio::runtime::Runtime;

/// A soft-deleting model: `delete()` stamps `deleted_at` and the row is hidden by
/// default thereafter.
#[derive(Model, Debug, Clone)]
#[model(table = "l14_notes", ordering = "id", soft_delete)]
struct Note {
    #[field(primary_key)]
    id: i64,
    #[field(max_length = 100)]
    body: String,
    deleted_at: Option<DateTime<Utc>>,
}

fn dsn() -> Option<String> {
    std::env::var("DELONIX_ORM_TEST_DSN")
        .ok()
        .filter(|s| !s.trim().is_empty())
}

fn runtime() -> &'static Runtime {
    static RT: std::sync::OnceLock<Runtime> = std::sync::OnceLock::new();
    RT.get_or_init(|| {
        tokio::runtime::Builder::new_multi_thread()
            .worker_threads(2)
            .enable_all()
            .build()
            .expect("a tokio runtime")
    })
}

#[test]
#[ignore = "needs a Postgres (DELONIX_ORM_TEST_DSN)"]
fn delete_hides_by_default_with_deleted_reveals_and_purge_removes() {
    let Some(dsn) = dsn() else {
        eprintln!("skipped: DELONIX_ORM_TEST_DSN is not set");
        return;
    };
    std::env::set_var(dorm_core::db::DSN_ENV, &dsn);

    runtime().block_on(async {
        dorm_core::db::execute("DROP TABLE IF EXISTS l14_notes", &[])
            .await
            .expect("clean");
        dorm_core::db::execute(
            "CREATE TABLE l14_notes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
             body TEXT NOT NULL, deleted_at TIMESTAMPTZ)",
            &[],
        )
        .await
        .expect("table");

        for body in ["one", "two", "three"] {
            Note::objects()
                .create(NewNote {
                    body: body.into(),
                    deleted_at: None,
                })
                .await
                .expect("insert");
        }
        assert_eq!(Note::objects().all().all().await.unwrap().len(), 3);

        // Find "two" and soft-delete it.
        let two = Note::objects()
            .filter(note::body.eq("two"))
            .get()
            .await
            .expect("two");
        let affected = Note::objects()
            .filter(note::id.eq(two.id))
            .delete()
            .await
            .expect("soft delete");
        assert_eq!(affected, 1);

        // Hidden by default now.
        let visible = Note::objects().all().all().await.unwrap();
        assert_eq!(visible.len(), 2, "the soft-deleted row is hidden");
        assert!(visible.iter().all(|n| n.body != "two"));

        // Revealed with `with_deleted`, and it carries a `deleted_at` stamp.
        let all = db::with_deleted(Note::objects().all().all())
            .await
            .expect("with_deleted");
        assert_eq!(all.len(), 3, "with_deleted reveals it");
        let revived = all.iter().find(|n| n.body == "two").unwrap();
        assert!(revived.deleted_at.is_some(), "it has a deletion stamp");

        // The row itself is still there physically (a soft delete, not a DELETE).
        let raw: i64 = dorm_core::db::sql("SELECT COUNT(*)::bigint FROM l14_notes", &[])
            .await
            .unwrap()[0]
            .try_get(0)
            .unwrap();
        assert_eq!(raw, 3, "soft delete did not remove the row");

        // Purge: hard-remove soft-deleted rows older than 0 seconds (all of them).
        let purged = dorm_core::scope::purge_soft_deleted(Note::meta(), 0)
            .await
            .expect("purge");
        assert_eq!(purged, 1, "the one soft-deleted row was purged");
        let raw: i64 = dorm_core::db::sql("SELECT COUNT(*)::bigint FROM l14_notes", &[])
            .await
            .unwrap()[0]
            .try_get(0)
            .unwrap();
        assert_eq!(raw, 2, "the purged row is physically gone");

        // A hard delete removes immediately, bypassing the soft path.
        let three = Note::objects()
            .filter(note::body.eq("three"))
            .get()
            .await
            .expect("three");
        db::with_hard_delete(Note::objects().filter(note::id.eq(three.id)).delete())
            .await
            .expect("hard delete");
        let raw: i64 = dorm_core::db::sql("SELECT COUNT(*)::bigint FROM l14_notes", &[])
            .await
            .unwrap()[0]
            .try_get(0)
            .unwrap();
        assert_eq!(raw, 1, "hard delete physically removed the row");
    });
}
