//! Aggregate result types follow PostgreSQL's promotion (A-F1), proven live.
//!
//! PostgreSQL promotes aggregate results: `SUM(int) → bigint`, `SUM(bigint) →
//! numeric`, `AVG(double) → double`. Before the fix the decoder expected the
//! SOURCE column's type, so `aggregate(Sum("big"))` over a `bigint` column failed
//! in `read_column` at runtime — the only numeric correctness bug the engagement
//! found (A-F1), latent because the live suite exercised only `COUNT`.
//!
//! This drives the REAL ORM aggregate path (`QuerySet::aggregate` → compiler →
//! `decode` → `read_column`) end to end: a successful decode at each promoted type
//! IS the proof, since the old (unpromoted) type would error here.
//!
//! ```text
//! DELONIX_ORM_TEST_DSN='host=/var/run/postgresql user=walter dbname=dorm_af1' \
//!   cargo test -p dorm-models --test aggregate_roundtrip_live -- --ignored --nocapture
//! ```

use dorm_core::expr::{AggKind, Aggregate};
use dorm_core::model::Model;
use dorm_core::prelude::*;
use dorm_derive::Model;
use tokio::runtime::Runtime;

/// One numeric row with the three source types whose promotion differs:
/// `small` (int), `big` (bigint) and `ratio` (double precision).
#[derive(Model, Debug, Clone)]
#[model(table = "l5_agg_metrics", ordering = "id")]
struct Metric {
    #[field(primary_key)]
    id: i64,
    small: i32,
    big: i64,
    ratio: f64,
}

fn dsn() -> Option<String> {
    std::env::var("DELONIX_ORM_TEST_DSN")
        .ok()
        .filter(|s| !s.trim().is_empty())
}

fn runtime() -> &'static Runtime {
    static RT: std::sync::OnceLock<Runtime> = std::sync::OnceLock::new();
    RT.get_or_init(|| {
        tokio::runtime::Builder::new_multi_thread()
            .worker_threads(2)
            .enable_all()
            .build()
            .expect("a tokio runtime")
    })
}

#[test]
#[ignore = "needs a Postgres (DELONIX_ORM_TEST_DSN)"]
fn aggregate_results_decode_at_the_promoted_type() {
    let Some(dsn) = dsn() else {
        eprintln!("skipped: DELONIX_ORM_TEST_DSN is not set");
        return;
    };
    std::env::set_var(dorm_core::db::DSN_ENV, &dsn);

    runtime().block_on(async {
        dorm_core::db::execute("DROP TABLE IF EXISTS l5_agg_metrics", &[])
            .await
            .expect("clean");
        dorm_core::db::execute(
            "CREATE TABLE l5_agg_metrics (\
               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
               small INT NOT NULL, big BIGINT NOT NULL, ratio DOUBLE PRECISION NOT NULL)",
            &[],
        )
        .await
        .expect("table");

        // `big` values exceed i32::MAX so SUM(big) is a genuine bigint→numeric case.
        for (small, big, ratio) in [(10i32, 3_000_000_000i64, 1.5f64), (20, 3_000_000_000, 2.5)] {
            Metric::objects()
                .create(NewMetric { small, big, ratio })
                .await
                .expect("insert");
        }

        // The headline A-F1 query: an aggregate over the whole table. If any result
        // type were still the source column's, `decode`/`read_column` would error
        // right here — so reaching the asserts at all is already the fix proven.
        let mut row = Metric::objects()
            .all()
            .aggregate(vec![
                Aggregate::new("sum_small", AggKind::Sum, "small"),
                Aggregate::new("sum_big", AggKind::Sum, "big"),
                Aggregate::new("avg_ratio", AggKind::Avg, "ratio"),
                Aggregate::new("avg_small", AggKind::Avg, "small"),
            ])
            .await
            .expect("the aggregate decodes at the PROMOTED types (A-F1)");

        // SUM(int) → bigint, decoded as I64.
        let sum_small = row.remove("sum_small").expect("sum_small present");
        assert!(
            matches!(sum_small, Value::I64(30)),
            "SUM(int) is a bigint: expected I64(30), got {sum_small:?}"
        );

        // SUM(bigint) → numeric, decoded as Decimal (this is the one that used to panic).
        let sum_big = row.remove("sum_big").expect("sum_big present");
        assert!(
            matches!(&sum_big, Value::Decimal(d) if d.normalize().to_string() == "6000000000"),
            "SUM(bigint) is a numeric: expected Decimal(6000000000), got {sum_big:?}"
        );

        // AVG(double) → double, decoded as F64.
        let avg_ratio = row.remove("avg_ratio").expect("avg_ratio present");
        assert!(
            matches!(avg_ratio, Value::F64(v) if (v - 2.0).abs() < 1e-9),
            "AVG(double) is a double: expected F64(2.0), got {avg_ratio:?}"
        );

        // AVG(int) → numeric, decoded as Decimal.
        let avg_small = row.remove("avg_small").expect("avg_small present");
        assert!(
            matches!(&avg_small, Value::Decimal(d) if d.normalize().to_string() == "15"),
            "AVG(int) is a numeric: expected Decimal(15), got {avg_small:?}"
        );

        dorm_core::db::execute("DROP TABLE IF EXISTS l5_agg_metrics", &[])
            .await
            .ok();
    });
}
