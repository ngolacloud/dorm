//! INET column + network lookups against a real PostgreSQL (ADR 0040 / L5-rede).
//!
//! ```text
//! DELONIX_ORM_TEST_DSN='host=127.0.0.1 port=5432 user=orm dbname=ormtest' \
//!   cargo test -p dorm-models --test network_types_live -- --ignored --nocapture
//! ```

use std::net::IpAddr;

use dorm_core::compiler::{compile_select, Plan};
use dorm_core::expr::Q;
use dorm_core::model::Model;
use dorm_core::prelude::*;
use dorm_derive::Model;
use tokio::runtime::Runtime;

/// A host with a native `INET` address — the IPAM building block.
#[derive(Model, Debug, Clone)]
#[model(table = "l5_hosts", ordering = "id")]
struct Host {
    #[field(primary_key)]
    id: i64,
    addr: IpAddr,
}

fn dsn() -> Option<String> {
    std::env::var("DELONIX_ORM_TEST_DSN")
        .ok()
        .filter(|s| !s.trim().is_empty())
}

fn runtime() -> &'static Runtime {
    static RT: std::sync::OnceLock<Runtime> = std::sync::OnceLock::new();
    RT.get_or_init(|| {
        tokio::runtime::Builder::new_multi_thread()
            .worker_threads(2)
            .enable_all()
            .build()
            .expect("a tokio runtime")
    })
}

/// Pure SQL-shape check (no database): the network lookup emits `<<` and casts the
/// text value to `inet` with the inference-safe `($n || '')::inet`, binding the
/// CIDR as text.
#[test]
fn a_network_lookup_emits_the_operator_and_casts_the_value_to_inet() {
    let mut plan = Plan::new(Host::meta());
    plan.filters
        .push(Q::new("addr__net_contained_by", "10.0.0.0/8"));
    let sql = compile_select(&plan).expect("compiles");
    assert!(
        sql.text.contains("<<"),
        "expected the containment operator: {}",
        sql.text
    );
    assert!(
        sql.text.contains("::inet"),
        "value cast to inet: {}",
        sql.text
    );
    assert_eq!(
        sql.params[0],
        Value::Text("10.0.0.0/8".into()),
        "CIDR bound as text"
    );
    // The inet SQL type is what the column is created as.
    assert_eq!(FieldType::Inet.sql_type(), "INET");
}

#[test]
#[ignore = "needs a Postgres (DELONIX_ORM_TEST_DSN)"]
fn inet_round_trips_and_containment_lookups_find_the_right_hosts() {
    let Some(dsn) = dsn() else {
        eprintln!("skipped: DELONIX_ORM_TEST_DSN is not set");
        return;
    };
    std::env::set_var(dorm_core::db::DSN_ENV, &dsn);

    runtime().block_on(async {
        dorm_core::db::execute("DROP TABLE IF EXISTS l5_hosts", &[])
            .await
            .expect("clean");
        dorm_core::db::execute(
            "CREATE TABLE l5_hosts (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, addr INET NOT NULL)",
            &[],
        )
        .await
        .expect("table");

        for ip in ["10.1.2.3", "10.99.0.1", "192.168.1.1", "172.16.0.5"] {
            Host::objects()
                .create(NewHost {
                    addr: ip.parse::<IpAddr>().unwrap(),
                })
                .await
                .expect("insert");
        }

        // Round-trip: a native INET read back as the same IpAddr.
        let one = Host::objects()
            .filter(host::addr.eq("10.1.2.3".parse::<IpAddr>().unwrap()))
            .get()
            .await
            .expect("exact inet match");
        assert_eq!(one.addr, "10.1.2.3".parse::<IpAddr>().unwrap());

        // contained_by: the two 10.x hosts are inside 10.0.0.0/8.
        let in_ten = Host::objects()
            .filter_str("addr__net_contained_by", "10.0.0.0/8")
            .all()
            .await
            .expect("net_contained_by");
        assert_eq!(in_ten.len(), 2, "two hosts in 10.0.0.0/8");
        assert!(in_ten
            .iter()
            .all(|h| h.addr.to_string().starts_with("10.")));

        // A tighter network catches only one.
        let n = Host::objects()
            .filter_str("addr__net_contained_by", "10.99.0.0/16")
            .count()
            .await
            .expect("count");
        assert_eq!(n, 1, "only 10.99.0.1 is in 10.99.0.0/16");

        // overlaps: 192.168.1.1 overlaps 192.168.0.0/16.
        let n = Host::objects()
            .filter_str("addr__net_overlaps", "192.168.0.0/16")
            .count()
            .await
            .expect("overlaps");
        assert_eq!(n, 1, "192.168.1.1 overlaps 192.168.0.0/16");

        // A network lookup on a non-inet column is refused before any SQL runs.
        let err = Host::objects()
            .filter_str("id__net_contains", "10.0.0.0/8")
            .count()
            .await
            .expect_err("a network lookup on a bigint column must be refused");
        assert!(err.to_string().contains("inet"), "got {err:?}");
    });
}
