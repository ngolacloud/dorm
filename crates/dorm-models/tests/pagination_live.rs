//! Keyset pagination against a real PostgreSQL (ADR 0024).
//!
//! Proves the three things that matter: pages tile the whole set with no gaps and
//! no duplicates even when the sort key has ties (the primary-key tiebreak makes
//! the order total); the SQL carries the keyset predicate and **no `OFFSET`**; and
//! a cursor minted for one query is refused by another.
//!
//! ```text
//! DELONIX_ORM_TEST_DSN='host=127.0.0.1 port=5432 user=orm dbname=ormtest' \
//!   cargo test -p dorm-models --test pagination_live -- --ignored --nocapture
//! ```

use dorm_core::compiler::{compile_select, Plan};
use dorm_core::prelude::*;
use dorm_derive::Model;
use tokio::runtime::Runtime;

/// A row whose sort key (`bucket`) deliberately has ties, so the pk tiebreak is
/// exercised. Declared ordering is `bucket`; the pagination appends `id`.
#[derive(Model, Debug, Clone)]
#[model(table = "pagination_items", ordering = "bucket")]
struct Item {
    #[field(primary_key)]
    id: i64,
    #[field(max_length = 20)]
    bucket: String,
    #[field(max_length = 40)]
    note: String,
}

fn dsn() -> Option<String> {
    std::env::var("DELONIX_ORM_TEST_DSN")
        .ok()
        .filter(|s| !s.trim().is_empty())
}

fn runtime() -> &'static Runtime {
    static RT: std::sync::OnceLock<Runtime> = std::sync::OnceLock::new();
    RT.get_or_init(|| {
        tokio::runtime::Builder::new_multi_thread()
            .worker_threads(2)
            .enable_all()
            .build()
            .expect("a tokio runtime")
    })
}

fn setup(dsn: &str) {
    static ONCE: std::sync::Once = std::sync::Once::new();
    const SCHEMA_LOCK: i64 = 0x0024_9a9e;
    ONCE.call_once(|| {
        // The library no longer defaults the cursor signing key; a consumer
        // configures it. This test installs the development key.
        dorm_core::cursor::set_dev_cursor_key();
        std::env::set_var(dorm_core::db::DSN_ENV, dsn);
        runtime().block_on(async {
            db::atomic(|_tx| async {
                dorm_core::db::execute("SELECT pg_advisory_xact_lock($1)", &[&SCHEMA_LOCK]).await?;
                dorm_core::db::execute(
                    "CREATE TABLE IF NOT EXISTS pagination_items (\
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
                       bucket TEXT NOT NULL, note TEXT NOT NULL)",
                    &[],
                )
                .await?;
                dorm_core::db::execute(
                    "CREATE INDEX IF NOT EXISTS pagination_items_bucket_id \
                       ON pagination_items (bucket, id)",
                    &[],
                )
                .await?;
                Ok(())
            })
            .await
            .expect("schema");
        });
    });
}

/// Pure SQL-shape check — runs without a database. The compiled keyset query has
/// the lexicographic tuple predicate and no `OFFSET`, and orders by the pk last.
#[test]
fn the_keyset_query_has_no_offset_and_a_tuple_predicate() {
    let mut plan = Plan::new(Item::meta());
    plan.paginate = true;
    plan.keyset = Some(vec![Value::Text("b".into()), Value::I64(5)]);
    plan.limit = Some(10);
    let sql = compile_select(&plan).expect("compiles");
    assert!(
        !sql.text.contains("OFFSET"),
        "keyset must not OFFSET: {}",
        sql.text
    );
    assert!(
        sql.text.contains(" OR "),
        "expected the OR-expanded tuple: {}",
        sql.text
    );
    assert!(
        sql.text.contains("ORDER BY") && sql.text.trim_end().ends_with("LIMIT 10"),
        "{}",
        sql.text
    );
    // The pk is the final ORDER BY term (the tiebreak).
    let order = &sql.text[sql.text.find("ORDER BY").unwrap()..];
    assert!(order.contains("\"id\""), "pk tiebreak missing: {order}");
}

#[test]
#[ignore = "needs a Postgres (DELONIX_ORM_TEST_DSN)"]
fn pages_tile_the_whole_set_with_no_gaps_or_duplicates() {
    let Some(dsn) = dsn() else {
        eprintln!("skipped: DELONIX_ORM_TEST_DSN is not set");
        return;
    };
    setup(&dsn);
    runtime().block_on(async {
        // A clean set unique to this test run would need a scoping column; instead
        // this test owns the table, so start it empty.
        dorm_core::db::execute("TRUNCATE pagination_items", &[])
            .await
            .expect("truncate");

        // 25 rows across three buckets — buckets repeat, so ordering by bucket
        // alone is ambiguous and the pk tiebreak is what makes paging correct.
        let mut news = Vec::new();
        for (bucket, n) in [("a", 10), ("b", 10), ("c", 5)] {
            for i in 0..n {
                news.push(NewItem {
                    bucket: bucket.into(),
                    note: format!("{bucket}-{i}"),
                });
            }
        }
        Item::objects().bulk_create(news).await.expect("seed");

        // Page through in tens, following the cursor.
        let mut seen: Vec<(String, i64)> = Vec::new();
        let mut cursor: Option<String> = None;
        let mut pages = 0;
        loop {
            let qs = Item::objects().all();
            let qs = match &cursor {
                Some(c) => qs.after(c).expect("cursor applies"),
                None => qs,
            };
            let page = qs.fetch_page(10).await.expect("page");
            pages += 1;
            for it in &page.items {
                seen.push((it.bucket.clone(), it.id));
            }
            match page.next {
                Some(c) => cursor = Some(c),
                None => break,
            }
            assert!(pages < 10, "pagination did not terminate");
        }

        // Every row exactly once: 25 rows, 3 pages (10 + 10 + 5).
        assert_eq!(seen.len(), 25, "every row returned exactly once");
        assert_eq!(pages, 3, "25 rows in pages of 10 is three pages");
        let mut unique = seen.clone();
        unique.sort();
        unique.dedup();
        assert_eq!(unique.len(), 25, "no duplicates across pages: {seen:?}");

        // And the global order is (bucket, id) ascending — the total order.
        let mut sorted = seen.clone();
        sorted.sort();
        assert_eq!(seen, sorted, "rows came back in the total order");

        // A cursor from this query is refused by a differently-filtered one.
        let page = Item::objects()
            .all()
            .fetch_page(10)
            .await
            .expect("first page");
        let c = page.next.expect("there is a next page");
        let err = Item::objects()
            .filter(item::bucket.eq("a"))
            .after(&c)
            .expect_err("a foreign cursor must be refused");
        assert!(err.to_string().contains("different query"), "got {err:?}");
    });
}
