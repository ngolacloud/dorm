//! Optimistic concurrency against a real PostgreSQL (ADR 0023).
//!
//! Skipped unless `DELONIX_ORM_TEST_DSN` is set, and `#[ignore]` besides — the
//! same convention as `typed_e2e.rs`. The model here is **local to this test
//! binary**: it registers into the inventory of this binary only, so the example
//! model set the other suites assert on is untouched.
//!
//! ```text
//! DELONIX_ORM_TEST_DSN='host=127.0.0.1 port=5432 user=orm dbname=ormtest' \
//!   cargo test -p dorm-models --test optimistic_live -- --ignored --nocapture
//! ```

use dorm_core::model::{etag, update_if_version, version_from_etag};
use dorm_core::prelude::*;
use dorm_derive::Model;
use tokio::runtime::Runtime;

/// A versioned row. `#[field(version)]` marks `rev` as the optimistic-lock
/// counter; `default = "0"` makes the database fill it in on insert.
#[derive(Model, Debug, Clone)]
#[model(table = "optimistic_documents", ordering = "id")]
struct Document {
    #[field(primary_key)]
    id: i64,
    #[field(max_length = 120)]
    title: String,
    #[field(version, default = "0")]
    rev: i64,
}

fn dsn() -> Option<String> {
    std::env::var("DELONIX_ORM_TEST_DSN")
        .ok()
        .filter(|s| !s.trim().is_empty())
}

fn runtime() -> &'static Runtime {
    static RT: std::sync::OnceLock<Runtime> = std::sync::OnceLock::new();
    RT.get_or_init(|| {
        tokio::runtime::Builder::new_multi_thread()
            .worker_threads(2)
            .enable_all()
            .build()
            .expect("a tokio runtime")
    })
}

fn setup(dsn: &str) {
    static ONCE: std::sync::Once = std::sync::Once::new();
    const SCHEMA_LOCK: i64 = 0x0023_d0c0;
    ONCE.call_once(|| {
        std::env::set_var(dorm_core::db::DSN_ENV, dsn);
        runtime().block_on(async {
            db::atomic(|_tx| async {
                dorm_core::db::execute("SELECT pg_advisory_xact_lock($1)", &[&SCHEMA_LOCK]).await?;
                dorm_core::db::execute(
                    "CREATE TABLE IF NOT EXISTS optimistic_documents (\
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
                       title TEXT NOT NULL, \
                       rev BIGINT NOT NULL DEFAULT 0)",
                    &[],
                )
                .await?;
                Ok(())
            })
            .await
            .expect("the schema is created");
        });
    });
}

/// The core proof: two readers of the same row, one writes, the other's stale
/// write is refused with `Error::Conflict` rather than silently clobbering it.
#[test]
#[ignore = "needs a Postgres (DELONIX_ORM_TEST_DSN)"]
fn a_stale_write_loses_the_optimistic_guard_and_a_fresh_one_wins() {
    let Some(dsn) = dsn() else {
        eprintln!("skipped: DELONIX_ORM_TEST_DSN is not set");
        return;
    };
    setup(&dsn);
    runtime().block_on(async {
        let created = Document::objects()
            .create(NewDocument {
                title: "draft".into(),
            })
            .await
            .expect("the document is created");
        assert_eq!(created.rev, 0, "a fresh row starts at version 0");

        // Two sessions read the same row at version 0.
        let mut writer_a = Document::objects()
            .filter(document::id.eq(created.id))
            .get()
            .await
            .expect("reader A loads the row");
        let mut writer_b = writer_a.clone();
        assert_eq!(writer_a.rev, 0);
        assert_eq!(writer_b.rev, 0);

        // A writes first and wins; its in-memory version advances to 1.
        writer_a.title = "edited by A".into();
        writer_a.save().await.expect("A's write succeeds");
        assert_eq!(writer_a.rev, 1, "a successful save advances the version");

        // B still holds version 0, so its write matches no row and is refused.
        writer_b.title = "edited by B".into();
        match writer_b.save().await {
            Err(Error::Conflict {
                expected, actual, ..
            }) => {
                assert_eq!(expected, 0);
                assert_eq!(actual, Some(1), "the database already moved to 1");
            }
            other => panic!("expected a version conflict, got {other:?}"),
        }

        // The row the database holds is A's, untouched by B's lost write.
        let current = Document::objects()
            .filter(document::id.eq(created.id))
            .get()
            .await
            .expect("re-read the row");
        assert_eq!(current.title, "edited by A");
        assert_eq!(current.rev, 1);

        // B re-reads and retries — now it wins, version 1 -> 2.
        let mut retry = current.clone();
        retry.title = "edited by B, retried".into();
        retry.save().await.expect("B's retry succeeds");
        assert_eq!(retry.rev, 2);

        // The explicit `If-Match` form: an ETag carries the expected version.
        let tag = etag(retry.rev);
        let expected = version_from_etag(&tag).expect("the etag decodes");
        let mut via_etag = retry.clone();
        via_etag.title = "set via etag".into();
        update_if_version(&mut via_etag, expected)
            .await
            .expect("the If-Match update succeeds at the expected version");
        assert_eq!(via_etag.rev, 3);

        // A second attempt at the now-stale etag version is refused.
        let mut stale = via_etag.clone();
        stale.rev = 2; // pretend an old ETag
        let err = update_if_version(&mut stale, 2).await.unwrap_err();
        assert!(matches!(err, Error::Conflict { .. }), "got {err:?}");
    });
}
