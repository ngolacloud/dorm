//! JSONB path lookups against a real PostgreSQL (ADR 0025).
//!
//! Proves `spec__cpu__gte` and friends reach into a JSONB column: the path is
//! extracted with each segment **bound**, cast to the type the comparison value
//! implies, and compared — numbers, nested paths and text all work.
//!
//! ```text
//! DELONIX_ORM_TEST_DSN='host=127.0.0.1 port=5432 user=orm dbname=ormtest' \
//!   cargo test -p dorm-models --test jsonb_live -- --ignored --nocapture
//! ```

use dorm_core::compiler::{compile_select, Plan};
use dorm_core::expr::Q;
use dorm_core::prelude::*;
use dorm_derive::Model;
use tokio::runtime::Runtime;

/// A row with a free-form JSONB `spec`, the shape a control plane keeps resource
/// requests in.
#[derive(Model, Debug, Clone)]
#[model(table = "jsonb_docs", ordering = "id")]
struct Doc {
    #[field(primary_key)]
    id: i64,
    spec: serde_json::Value,
}

fn dsn() -> Option<String> {
    std::env::var("DELONIX_ORM_TEST_DSN")
        .ok()
        .filter(|s| !s.trim().is_empty())
}

fn runtime() -> &'static Runtime {
    static RT: std::sync::OnceLock<Runtime> = std::sync::OnceLock::new();
    RT.get_or_init(|| {
        tokio::runtime::Builder::new_multi_thread()
            .worker_threads(2)
            .enable_all()
            .build()
            .expect("a tokio runtime")
    })
}

fn setup(dsn: &str) {
    static ONCE: std::sync::Once = std::sync::Once::new();
    const SCHEMA_LOCK: i64 = 0x0025_1b0b;
    ONCE.call_once(|| {
        std::env::set_var(dorm_core::db::DSN_ENV, dsn);
        runtime().block_on(async {
            db::atomic(|_tx| async {
                dorm_core::db::execute("SELECT pg_advisory_xact_lock($1)", &[&SCHEMA_LOCK]).await?;
                dorm_core::db::execute(
                    "CREATE TABLE IF NOT EXISTS jsonb_docs (\
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
                       spec JSONB NOT NULL)",
                    &[],
                )
                .await?;
                Ok(())
            })
            .await
            .expect("schema");
        });
    });
}

/// Pure SQL-shape check — no database. The path is bound, not spliced, and the
/// numeric value drives a `::numeric` cast.
#[test]
fn a_jsonb_path_lookup_binds_the_path_and_casts_by_value() {
    let mut plan = Plan::new(Doc::meta());
    plan.filters.push(Q::new("spec__cpu__gte", 4i64));
    let sql = compile_select(&plan).expect("compiles");
    assert!(
        sql.text.contains("jsonb_extract_path_text"),
        "expected a JSONB extract: {}",
        sql.text
    );
    // The cast is the value's native type (i64 → bigint), not a wider one — see
    // ADR 0025 and the compiler's note on parameter-type inference.
    assert!(sql.text.contains("::bigint"), "bigint cast: {}", sql.text);
    assert!(sql.text.contains(">="), "{}", sql.text);
    // The path segment `cpu` is bound, never in the text.
    assert!(
        !sql.text.contains("cpu"),
        "path must be bound: {}",
        sql.text
    );
    assert_eq!(sql.params[0], Value::Text("cpu".into()));
    assert_eq!(sql.params[1], Value::I64(4));
}

#[test]
#[ignore = "needs a Postgres (DELONIX_ORM_TEST_DSN)"]
fn paths_reach_into_the_document_for_numbers_text_and_nesting() {
    let Some(dsn) = dsn() else {
        eprintln!("skipped: DELONIX_ORM_TEST_DSN is not set");
        return;
    };
    setup(&dsn);
    runtime().block_on(async {
        dorm_core::db::execute("TRUNCATE jsonb_docs", &[])
            .await
            .expect("truncate");

        let specs = [
            serde_json::json!({"cpu": 2, "zone": "lis", "limits": {"mem": 128}}),
            serde_json::json!({"cpu": 4, "zone": "lis", "limits": {"mem": 512}}),
            serde_json::json!({"cpu": 8, "zone": "jnb", "limits": {"mem": 1024}}),
        ];
        for spec in specs {
            Doc::objects()
                .create(NewDoc { spec })
                .await
                .expect("insert");
        }

        // A numeric comparison inside the document.
        let n = Doc::objects()
            .filter_str("spec__cpu__gte", 4i64)
            .count()
            .await
            .expect("cpu>=4");
        assert_eq!(n, 2, "two docs have cpu >= 4");

        // A text key, exact.
        let n = Doc::objects()
            .filter_str("spec__zone", "lis")
            .count()
            .await
            .expect("zone=lis");
        assert_eq!(n, 2, "two docs are in zone lis");

        // A nested path, numeric.
        let n = Doc::objects()
            .filter_str("spec__limits__mem__gte", 512i64)
            .count()
            .await
            .expect("mem>=512");
        assert_eq!(n, 2, "two docs have mem >= 512");

        // Combined: cpu in a range and a zone.
        let n = Doc::objects()
            .filter(Q::new("spec__cpu__gte", 4i64) & Q::new("spec__zone", "lis"))
            .count()
            .await
            .expect("combined");
        assert_eq!(n, 1, "only the 4-cpu lis doc matches both");
    });
}
