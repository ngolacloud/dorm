//! A durable PostgreSQL job queue for DORM (ADR 0027).
//!
//! The pieces a control plane's reconcilers need: durable work that survives a
//! restart, claimed without two workers taking the same job (`FOR UPDATE SKIP
//! LOCKED`), scheduled for the future, ordered by priority, retried with backoff
//! and dead-lettered when it keeps failing, and **at most one active job per
//! resource** (a unique key). Plus expiring **leases** so a single reconciler is
//! active per partition.
//!
//! Optional and one-way: `dorm-core` never depends on this crate, so a project
//! that does not use it has an unchanged dependency graph.

use dorm_core::db;
use dorm_core::error::{Error, Result};
use dorm_core::value::Value;

/// The durable job table.
pub const JOBS: &str = "dorm_jobs";
/// The leases table (leader election).
pub const LEASES: &str = "dorm_leases";

/// The DDL that creates the job and lease tables. `IF NOT EXISTS` throughout.
pub fn migrations() -> Vec<String> {
    vec![
        format!(
            "CREATE TABLE IF NOT EXISTS {JOBS} (\
               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
               queue TEXT NOT NULL, \
               kind TEXT NOT NULL, \
               payload JSONB NOT NULL DEFAULT '{{}}'::jsonb, \
               priority INT NOT NULL DEFAULT 0, \
               run_at TIMESTAMPTZ NOT NULL DEFAULT now(), \
               state TEXT NOT NULL DEFAULT 'pending', \
               attempts INT NOT NULL DEFAULT 0, \
               max_attempts INT NOT NULL DEFAULT 5, \
               last_error TEXT, \
               unique_key TEXT, \
               locked_at TIMESTAMPTZ, \
               locked_by TEXT, \
               created_at TIMESTAMPTZ NOT NULL DEFAULT now(), \
               updated_at TIMESTAMPTZ NOT NULL DEFAULT now())"
        ),
        // The dequeue path: by queue, pending, highest priority, oldest due first.
        format!(
            "CREATE INDEX IF NOT EXISTS {JOBS}_dequeue \
             ON {JOBS} (queue, state, priority DESC, run_at, id)"
        ),
        // At most one *active* (pending or running) job per (queue, unique_key).
        format!(
            "CREATE UNIQUE INDEX IF NOT EXISTS {JOBS}_unique_active \
             ON {JOBS} (queue, unique_key) \
             WHERE unique_key IS NOT NULL AND state IN ('pending', 'running')"
        ),
        format!(
            "CREATE TABLE IF NOT EXISTS {LEASES} (\
               name TEXT PRIMARY KEY, \
               holder TEXT NOT NULL, \
               expires_at TIMESTAMPTZ NOT NULL)"
        ),
    ]
}

/// A claimed job handed to a worker.
#[derive(Debug, Clone)]
pub struct Job {
    pub id: i64,
    pub kind: String,
    pub payload: serde_json::Value,
    pub attempts: i32,
    pub max_attempts: i32,
}

/// Options for [`enqueue`].
#[derive(Debug, Clone)]
pub struct EnqueueOpts {
    /// Higher runs first. Default `0`.
    pub priority: i32,
    /// Delay before the job is eligible, in milliseconds. Default `0` (now).
    pub delay_ms: i64,
    /// Attempts before the job is dead-lettered. Default `5`.
    pub max_attempts: i32,
    /// When set, at most one active job per `(queue, unique_key)` — a duplicate
    /// enqueue is a no-op. For "one pending reconcile per resource".
    pub unique_key: Option<String>,
}

impl Default for EnqueueOpts {
    fn default() -> Self {
        EnqueueOpts {
            priority: 0,
            delay_ms: 0,
            max_attempts: 5,
            unique_key: None,
        }
    }
}

/// The millisecond count, bound as **text**, for `($n || ' milliseconds')::interval`.
///
/// The number travels as text and is concatenated in SQL, which forces the
/// server to infer the parameter as `text` (what we send). A direct
/// `$n::interval` would make the server infer the parameter as `interval` and
/// reject the text bytes (SQLSTATE `08P01`) — the same parameter-type-inference
/// trap the JSONB cast hit (ADR 0025).
fn millis(ms: i64) -> Value {
    Value::Text(ms.to_string())
}

/// Enqueue a job. Returns its id, or `None` when a `unique_key` collided with an
/// already-active job (the queue already has this work pending).
pub async fn enqueue(
    queue: &str,
    kind: &str,
    payload: &serde_json::Value,
    opts: EnqueueOpts,
) -> Result<Option<i64>> {
    let unique = opts.unique_key.map(Value::Text).unwrap_or(Value::Null);
    let rows = db::sql(
        &format!(
            "INSERT INTO {JOBS} (queue, kind, payload, priority, run_at, max_attempts, unique_key) \
             VALUES ($1, $2, $3, $4, now() + ($5 || ' milliseconds')::interval, $6, $7) \
             ON CONFLICT DO NOTHING \
             RETURNING id"
        ),
        &[
            Value::Text(queue.to_string()),
            Value::Text(kind.to_string()),
            Value::Json(payload.clone()),
            Value::I32(opts.priority),
            millis(opts.delay_ms),
            Value::I32(opts.max_attempts),
            unique,
        ],
    )
    .await?;
    match rows.first() {
        Some(r) => Ok(Some(r.try_get::<i64>(0)?)),
        None => Ok(None),
    }
}

/// Claim the next due job on `queue` for `worker`, or `None` when there is none.
///
/// The claim is a single `UPDATE` whose target is chosen with `FOR UPDATE SKIP
/// LOCKED`, so two workers racing for the same queue take different jobs rather
/// than one blocking or both grabbing the same row.
pub async fn dequeue(queue: &str, worker: &str) -> Result<Option<Job>> {
    let rows = db::sql(
        &format!(
            "UPDATE {JOBS} SET state = 'running', locked_at = now(), locked_by = $2, \
                 attempts = attempts + 1, updated_at = now() \
             WHERE id = (\
                 SELECT id FROM {JOBS} \
                 WHERE queue = $1 AND state = 'pending' AND run_at <= now() \
                 ORDER BY priority DESC, run_at, id \
                 FOR UPDATE SKIP LOCKED LIMIT 1) \
             RETURNING id, kind, payload::text, attempts, max_attempts"
        ),
        &[
            Value::Text(queue.to_string()),
            Value::Text(worker.to_string()),
        ],
    )
    .await?;
    let Some(r) = rows.first() else {
        return Ok(None);
    };
    let payload_text = r.try_get::<String>(2)?;
    let payload = serde_json::from_str(&payload_text)
        .map_err(|e| Error::Db(format!("job payload is not JSON: {e}")))?;
    Ok(Some(Job {
        id: r.try_get::<i64>(0)?,
        kind: r.try_get::<String>(1)?,
        payload,
        attempts: r.try_get::<i32>(3)?,
        max_attempts: r.try_get::<i32>(4)?,
    }))
}

/// Mark a job done.
pub async fn complete(id: i64) -> Result<()> {
    db::run(
        &format!("UPDATE {JOBS} SET state = 'done', updated_at = now() WHERE id = $1"),
        &[Value::I64(id)],
    )
    .await?;
    Ok(())
}

/// Record a failure: reschedule with `backoff_ms` while attempts remain, else
/// dead-letter (`state = 'dead'`). Returns `true` when the job was dead-lettered.
pub async fn fail(id: i64, error: &str, backoff_ms: i64) -> Result<bool> {
    let rows = db::sql(
        &format!(
            "UPDATE {JOBS} SET \
                 state = CASE WHEN attempts >= max_attempts THEN 'dead' ELSE 'pending' END, \
                 run_at = now() + ($3 || ' milliseconds')::interval, \
                 last_error = $2, locked_by = NULL, locked_at = NULL, updated_at = now() \
             WHERE id = $1 \
             RETURNING state"
        ),
        &[
            Value::I64(id),
            Value::Text(error.to_string()),
            millis(backoff_ms),
        ],
    )
    .await?;
    Ok(rows
        .first()
        .map(|r| r.try_get::<String>(0).map(|s| s == "dead"))
        .transpose()?
        .unwrap_or(false))
}

/// Claim one job and run `handler`, completing it on success or failing it (with
/// `backoff_ms`) on error. Returns `true` when a job was processed, `false` when
/// the queue was empty — a worker loops on this with a sleep on `false`.
pub async fn run_once<H, Fut>(
    queue: &str,
    worker: &str,
    backoff_ms: i64,
    handler: H,
) -> Result<bool>
where
    H: FnOnce(Job) -> Fut,
    Fut: std::future::Future<Output = Result<()>>,
{
    let Some(job) = dequeue(queue, worker).await? else {
        return Ok(false);
    };
    let id = job.id;
    match handler(job).await {
        Ok(()) => complete(id).await?,
        Err(e) => {
            let dead = fail(id, &e.to_string(), backoff_ms).await?;
            if dead {
                tracing::warn!(target: "dorm::jobs", job = id, error = %e, "job dead-lettered");
            }
        }
    }
    Ok(true)
}

/// Acquire or renew a lease named `name` for `holder`, valid for `ttl_ms`.
/// Returns `true` when held (fresh, expired-and-taken, or renewed by the same
/// holder), `false` when another holder still has it — the leader-election
/// primitive for "one active reconciler per partition" (ADR 0027).
pub async fn acquire_lease(name: &str, holder: &str, ttl_ms: i64) -> Result<bool> {
    let rows = db::sql(
        &format!(
            "INSERT INTO {LEASES} (name, holder, expires_at) \
             VALUES ($1, $2, now() + ($3 || ' milliseconds')::interval) \
             ON CONFLICT (name) DO UPDATE SET holder = EXCLUDED.holder, expires_at = EXCLUDED.expires_at \
             WHERE {LEASES}.expires_at < now() OR {LEASES}.holder = EXCLUDED.holder \
             RETURNING holder"
        ),
        &[
            Value::Text(name.to_string()),
            Value::Text(holder.to_string()),
            millis(ttl_ms),
        ],
    )
    .await?;
    Ok(!rows.is_empty())
}

/// Release a lease held by `holder` (a no-op if someone else holds it now).
pub async fn release_lease(name: &str, holder: &str) -> Result<()> {
    db::run(
        &format!("DELETE FROM {LEASES} WHERE name = $1 AND holder = $2"),
        &[
            Value::Text(name.to_string()),
            Value::Text(holder.to_string()),
        ],
    )
    .await?;
    Ok(())
}

/// How many jobs are pending on `queue` — the queue depth.
pub async fn depth(queue: &str) -> Result<i64> {
    let rows = db::sql(
        &format!("SELECT COUNT(*)::bigint FROM {JOBS} WHERE queue = $1 AND state = 'pending'"),
        &[Value::Text(queue.to_string())],
    )
    .await?;
    rows.first()
        .ok_or_else(|| Error::Db("COUNT returned no row".into()))?
        .try_get::<i64>(0)
}

/// The age, in seconds, of the oldest pending job on `queue`, or `None` when the
/// queue is empty — the queue's age metric.
pub async fn oldest_age_secs(queue: &str) -> Result<Option<f64>> {
    let rows = db::sql(
        &format!(
            "SELECT EXTRACT(EPOCH FROM (now() - MIN(run_at)))::double precision \
             FROM {JOBS} WHERE queue = $1 AND state = 'pending'"
        ),
        &[Value::Text(queue.to_string())],
    )
    .await?;
    match rows.first() {
        Some(r) => Ok(r.try_get::<f64>(0).ok()),
        None => Ok(None),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_migrations_create_the_tables_and_the_unique_active_index() {
        let ddl = migrations().join("\n");
        assert!(ddl.contains(JOBS));
        assert!(ddl.contains(LEASES));
        assert!(ddl.contains(&format!("{JOBS}_unique_active")));
        assert!(
            !ddl.contains("SKIP LOCKED"),
            "SKIP LOCKED is in dequeue, not the DDL"
        );
        assert!(ddl.contains("state IN ('pending', 'running')"));
    }

    #[test]
    fn enqueue_opts_default_to_priority_zero_and_five_attempts() {
        let o = EnqueueOpts::default();
        assert_eq!(o.priority, 0);
        assert_eq!(o.max_attempts, 5);
        assert_eq!(o.delay_ms, 0);
        assert!(o.unique_key.is_none());
    }
}
