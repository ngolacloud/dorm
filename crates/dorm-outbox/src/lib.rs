//! A generic transactional outbox/inbox for DORM (ADR 0026).
//!
//! The pattern: a business write and the event announcing it land in the **same**
//! transaction, so there is never an event without the write nor a write without
//! the event. The event goes into an append-only [`dorm_outbox`](OUTBOX); nothing
//! is deleted on consumption. Independent consumers each track their own
//! [`position`](CURSOR), so two of them see the same events (fan-out) and neither
//! destroys what the other has not read yet.
//!
//! Delivery is **at-least-once** (the handler runs, then the cursor advances in a
//! separate step — a crash in between re-delivers). A handler that is not
//! naturally idempotent gets **exactly-once effect** by guarding on the
//! [`inbox`](record_once): the second attempt at the same `message_id` is a no-op.
//!
//! This crate is optional and depends only on `dorm-core`; the core never depends
//! on it, so a project that does not use it has an unchanged dependency graph.

use dorm_core::db;
use dorm_core::error::{Error, Result};
use dorm_core::value::Value;

/// The append-only event table.
pub const OUTBOX: &str = "dorm_outbox";
/// Per-consumer, per-topic read position.
pub const CURSOR: &str = "dorm_outbox_cursor";
/// Idempotency keys for non-idempotent consumers.
pub const INBOX: &str = "dorm_inbox";
/// Events a consumer gave up on, kept for inspection and replay.
pub const DEAD: &str = "dorm_outbox_dead";

/// The DDL that creates the outbox tables. Appended to a migration's statements,
/// exactly as `dorm-rag` does its own (ADR 0019/0026). `IF NOT EXISTS` throughout,
/// so a second run is a no-op.
pub fn migrations() -> Vec<String> {
    vec![
        format!(
            "CREATE TABLE IF NOT EXISTS {OUTBOX} (\
               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
               topic TEXT NOT NULL, \
               payload JSONB NOT NULL, \
               created_at TIMESTAMPTZ NOT NULL DEFAULT now())"
        ),
        format!("CREATE INDEX IF NOT EXISTS {OUTBOX}_topic_id ON {OUTBOX} (topic, id)"),
        format!(
            "CREATE TABLE IF NOT EXISTS {CURSOR} (\
               consumer TEXT NOT NULL, topic TEXT NOT NULL, \
               position BIGINT NOT NULL DEFAULT 0, \
               updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), \
               PRIMARY KEY (consumer, topic))"
        ),
        format!(
            "CREATE TABLE IF NOT EXISTS {INBOX} (\
               consumer TEXT NOT NULL, message_id TEXT NOT NULL, \
               processed_at TIMESTAMPTZ NOT NULL DEFAULT now(), \
               PRIMARY KEY (consumer, message_id))"
        ),
        format!(
            "CREATE TABLE IF NOT EXISTS {DEAD} (\
               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
               consumer TEXT NOT NULL, outbox_id BIGINT NOT NULL, topic TEXT NOT NULL, \
               payload JSONB NOT NULL, error TEXT NOT NULL, \
               failed_at TIMESTAMPTZ NOT NULL DEFAULT now())"
        ),
    ]
}

/// One event, as a consumer sees it.
#[derive(Debug, Clone)]
pub struct Event {
    pub id: i64,
    pub topic: String,
    pub payload: serde_json::Value,
}

/// Publish an event — **only inside a transaction** (`db::atomic`). Outside one it
/// is an error, which is what makes this an outbox: the event is written in the
/// same transaction as the business change, so the two commit or roll back
/// together. Returns the new event id.
pub async fn publish(topic: &str, payload: &serde_json::Value) -> Result<i64> {
    if !db::in_transaction() {
        return Err(Error::Config(
            "outbox::publish must run inside db::atomic — the event commits with the write".into(),
        ));
    }
    let rows = db::sql(
        &format!("INSERT INTO {OUTBOX} (topic, payload) VALUES ($1, $2) RETURNING id"),
        &[Value::Text(topic.to_string()), Value::Json(payload.clone())],
    )
    .await?;
    rows.first()
        .ok_or_else(|| Error::Db("the outbox insert returned no id".into()))?
        .try_get::<i64>(0)
}

/// Record that `consumer` has handled `message_id`, returning `true` when it is
/// newly recorded and `false` when it was already there — the idempotency guard a
/// non-idempotent handler checks for exactly-once effect under at-least-once
/// delivery. Runs in the caller's transaction when there is one.
pub async fn record_once(consumer: &str, message_id: &str) -> Result<bool> {
    let affected = db::run(
        &format!(
            "INSERT INTO {INBOX} (consumer, message_id) VALUES ($1, $2) ON CONFLICT DO NOTHING"
        ),
        &[
            Value::Text(consumer.to_string()),
            Value::Text(message_id.to_string()),
        ],
    )
    .await?;
    Ok(affected == 1)
}

/// How a relay pass behaves.
#[derive(Debug, Clone, Copy)]
pub struct RelayConfig {
    /// Events pulled per pass.
    pub batch: i64,
    /// Attempts before an event is dead-lettered.
    pub max_attempts: u32,
    /// Base backoff between attempts; doubles each attempt, capped at 30× base.
    pub backoff_base_ms: u64,
}

impl Default for RelayConfig {
    fn default() -> Self {
        RelayConfig {
            batch: 100,
            max_attempts: 5,
            backoff_base_ms: 50,
        }
    }
}

/// What one relay pass did.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct RelayStats {
    pub processed: u64,
    pub dead_lettered: u64,
}

/// Ensure the cursor row exists and read its position.
async fn position(consumer: &str, topic: &str) -> Result<i64> {
    db::run(
        &format!("INSERT INTO {CURSOR} (consumer, topic) VALUES ($1, $2) ON CONFLICT DO NOTHING"),
        &[
            Value::Text(consumer.to_string()),
            Value::Text(topic.to_string()),
        ],
    )
    .await?;
    let rows = db::sql(
        &format!("SELECT position FROM {CURSOR} WHERE consumer = $1 AND topic = $2"),
        &[
            Value::Text(consumer.to_string()),
            Value::Text(topic.to_string()),
        ],
    )
    .await?;
    rows.first()
        .ok_or_else(|| Error::Db("the cursor row vanished".into()))?
        .try_get::<i64>(0)
}

/// Advance the cursor to `id`, never backwards (so a slower concurrent worker
/// cannot rewind it).
async fn advance(consumer: &str, topic: &str, id: i64) -> Result<()> {
    db::run(
        &format!(
            "UPDATE {CURSOR} SET position = $3, updated_at = now() \
             WHERE consumer = $1 AND topic = $2 AND position < $3"
        ),
        &[
            Value::Text(consumer.to_string()),
            Value::Text(topic.to_string()),
            Value::I64(id),
        ],
    )
    .await?;
    Ok(())
}

async fn dead_letter(consumer: &str, ev: &Event, error: &str) -> Result<()> {
    db::run(
        &format!(
            "INSERT INTO {DEAD} (consumer, outbox_id, topic, payload, error) \
             VALUES ($1, $2, $3, $4, $5)"
        ),
        &[
            Value::Text(consumer.to_string()),
            Value::I64(ev.id),
            Value::Text(ev.topic.clone()),
            Value::Json(ev.payload.clone()),
            Value::Text(error.to_string()),
        ],
    )
    .await?;
    Ok(())
}

fn backoff(cfg: &RelayConfig, attempt: u32) -> std::time::Duration {
    let mult = 1u64 << attempt.min(5); // 1,2,4,…,32
    std::time::Duration::from_millis(
        cfg.backoff_base_ms
            .saturating_mul(mult)
            .min(cfg.backoff_base_ms * 30),
    )
}

/// Drain the events `consumer` has not yet seen for `topic`, newest cursor first,
/// calling `handler` for each. On success the cursor advances past the event; on
/// repeated failure the event is dead-lettered and the cursor advances so the
/// consumer does not stall. Returns what the pass did; call it again for the next
/// batch (a worker loops on it with a sleep when empty).
///
/// At-least-once: if the process dies after `handler` succeeds but before the
/// cursor advances, the event is re-delivered — the handler must be idempotent, or
/// guard on [`record_once`].
pub async fn relay<H, Fut>(
    consumer: &str,
    topic: &str,
    cfg: RelayConfig,
    mut handler: H,
) -> Result<RelayStats>
where
    H: FnMut(Event) -> Fut,
    Fut: std::future::Future<Output = Result<()>>,
{
    let pos = position(consumer, topic).await?;
    let rows = db::sql(
        &format!(
            "SELECT id, topic, payload::text FROM {OUTBOX} \
             WHERE topic = $1 AND id > $2 ORDER BY id LIMIT $3"
        ),
        &[
            Value::Text(topic.to_string()),
            Value::I64(pos),
            Value::I64(cfg.batch),
        ],
    )
    .await?;

    let mut stats = RelayStats::default();
    for row in &rows {
        let id = row.try_get::<i64>(0)?;
        let topic_s = row.try_get::<String>(1)?;
        let payload_text = row.try_get::<String>(2)?;
        let payload: serde_json::Value = serde_json::from_str(&payload_text)
            .map_err(|e| Error::Db(format!("outbox payload is not JSON: {e}")))?;
        let ev = Event {
            id,
            topic: topic_s,
            payload,
        };

        let mut attempt = 0u32;
        loop {
            match handler(ev.clone()).await {
                Ok(()) => {
                    advance(consumer, topic, ev.id).await?;
                    stats.processed += 1;
                    break;
                }
                Err(e) => {
                    attempt += 1;
                    if attempt >= cfg.max_attempts {
                        dead_letter(consumer, &ev, &e.to_string()).await?;
                        advance(consumer, topic, ev.id).await?;
                        stats.dead_lettered += 1;
                        tracing::warn!(target: "dorm::outbox", consumer, event = ev.id, error = %e, "event dead-lettered");
                        break;
                    }
                    tokio::time::sleep(backoff(&cfg, attempt)).await;
                }
            }
        }
    }
    Ok(stats)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_migrations_create_the_four_tables() {
        let ddl = migrations().join("\n");
        for t in [OUTBOX, CURSOR, INBOX, DEAD] {
            assert!(ddl.contains(t), "missing table {t}");
        }
        // The outbox index keeps the per-topic drain on an index, not a scan.
        assert!(ddl.contains(&format!("{OUTBOX}_topic_id")));
    }

    #[tokio::test]
    async fn publish_outside_a_transaction_is_refused_before_touching_the_database() {
        let e = publish("t", &serde_json::json!({}))
            .await
            .unwrap_err()
            .to_string();
        assert!(e.contains("inside db::atomic"), "{e}");
    }

    #[test]
    fn backoff_grows_and_caps() {
        let cfg = RelayConfig {
            backoff_base_ms: 10,
            ..Default::default()
        };
        assert!(backoff(&cfg, 1) < backoff(&cfg, 3));
        // Capped, never unbounded.
        assert!(backoff(&cfg, 50) <= std::time::Duration::from_millis(10 * 30));
    }
}
