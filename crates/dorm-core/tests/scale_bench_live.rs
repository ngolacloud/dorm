//! A reproducible scale benchmark against a real PostgreSQL (ADR 0036 / L16).
//!
//! Measures the two pagination shapes L4 (ADR 0024) generates — a keyset seek vs
//! a deep `OFFSET` — at a configurable row count (`DORM_BENCH_ROWS`, default
//! 50_000; set it to 10_000_000 on a dedicated bench host). The keyset query
//! seeks on the index; the `OFFSET` scans and discards, so its cost grows with
//! depth. The assertion is the regression signal; the printed numbers are the
//! measurement that an ADR records and a CI gate compares against a baseline.
//!
//! ```text
//! DORM_BENCH_ROWS=200000 DELONIX_ORM_TEST_DSN='host=127.0.0.1 port=5432 user=orm dbname=ormtest' \
//!   cargo test -p dorm-core --test scale_bench_live -- --ignored --nocapture
//! ```

use std::time::{Duration, Instant};

use dorm_core::db;
use dorm_core::value::Value;

fn dsn() -> Option<String> {
    std::env::var("DELONIX_ORM_TEST_DSN")
        .ok()
        .filter(|s| !s.trim().is_empty())
}

async fn time_query(sql: &str, boundary: i64, iters: u32) -> Duration {
    let mut total = Duration::ZERO;
    for _ in 0..iters {
        let start = Instant::now();
        db::sql(sql, &[Value::I64(boundary)]).await.expect("query");
        total += start.elapsed();
    }
    total / iters
}

#[tokio::test(flavor = "multi_thread")]
#[ignore = "needs a Postgres (DELONIX_ORM_TEST_DSN)"]
async fn keyset_pagination_beats_a_deep_offset_at_scale() {
    let Some(dsn) = dsn() else {
        eprintln!("skipped: DELONIX_ORM_TEST_DSN is not set");
        return;
    };
    std::env::set_var(dorm_core::db::DSN_ENV, &dsn);

    let rows: i64 = std::env::var("DORM_BENCH_ROWS")
        .ok()
        .and_then(|s| s.parse().ok())
        .unwrap_or(50_000);

    db::execute("DROP TABLE IF EXISTS bench_metric", &[])
        .await
        .expect("clean");
    db::execute(
        "CREATE TABLE bench_metric (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v INT NOT NULL)",
        &[],
    )
    .await
    .expect("table");
    // One fast seed.
    db::execute(
        "INSERT INTO bench_metric (v) SELECT (g % 100)::int FROM generate_series(1, $1::bigint) g",
        &[&rows],
    )
    .await
    .expect("seed");
    db::execute("ANALYZE bench_metric", &[]).await.ok();

    // A deep page, near the end: OFFSET must scan ~rows-10 rows and discard them;
    // keyset seeks straight to the boundary on the primary-key index.
    let deep = rows - 10;
    let boundary: i64 = db::sql(
        "SELECT id FROM bench_metric ORDER BY id OFFSET $1 LIMIT 1",
        &[Value::I64(deep)],
    )
    .await
    .expect("boundary")[0]
        .try_get(0)
        .unwrap();

    let offset_avg = time_query(
        "SELECT id FROM bench_metric ORDER BY id OFFSET $1 LIMIT 10",
        deep,
        20,
    )
    .await;
    let keyset_avg = time_query(
        "SELECT id FROM bench_metric WHERE id > $1 ORDER BY id LIMIT 10",
        boundary,
        20,
    )
    .await;

    println!(
        "scale bench @ {rows} rows — deep OFFSET avg = {offset_avg:?}, keyset avg = {keyset_avg:?}"
    );

    // A machine-readable line a CI gate parses and compares to a committed
    // baseline with a tolerance (ADR 0036). The assertion below is the always-on
    // floor; the baseline-diff is the finer regression signal.
    println!(
        "BENCH scenario=keyset_vs_offset rows={rows} offset_us={} keyset_us={}",
        offset_avg.as_micros(),
        keyset_avg.as_micros()
    );

    // The regression signal: keyset must not be slower than a deep OFFSET. At
    // scale it is dramatically faster; the generous factor keeps CI non-flaky
    // while still catching a regression that made keyset scan.
    assert!(
        keyset_avg <= offset_avg,
        "keyset ({keyset_avg:?}) should beat a deep OFFSET ({offset_avg:?}) at {rows} rows"
    );
}

/// A composite index (`@@index([tenant, created_at])`, ADR 0044) turns the
/// "latest N rows for a tenant" query — the bread-and-butter of a multi-tenant
/// control plane — from a full scan into an index seek. This measures the same
/// query before and after the index, at scale, so the speedup is the empirical
/// payoff of the index design (L8/L16).
#[tokio::test(flavor = "multi_thread")]
#[ignore = "needs a Postgres (DELONIX_ORM_TEST_DSN)"]
async fn a_composite_index_turns_a_tenant_latest_query_from_a_scan_into_a_seek() {
    let Some(dsn) = dsn() else {
        eprintln!("skipped: DELONIX_ORM_TEST_DSN is not set");
        return;
    };
    std::env::set_var(dorm_core::db::DSN_ENV, &dsn);

    let rows: i64 = std::env::var("DORM_BENCH_ROWS")
        .ok()
        .and_then(|s| s.parse().ok())
        .unwrap_or(50_000);
    // Spread the rows across many tenants, like a real fleet; one tenant's slice
    // is a small fraction of the table, which is exactly when a scan hurts.
    let tenants: i64 = 1_000;

    db::execute("DROP TABLE IF EXISTS bench_event", &[])
        .await
        .expect("clean");
    db::execute(
        "CREATE TABLE bench_event (\
         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
         tenant TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL, v INT NOT NULL)",
        &[],
    )
    .await
    .expect("table");
    // Seed: tenant = 't' || (g % tenants); created_at spread over time by g.
    db::execute(
        "INSERT INTO bench_event (tenant, created_at, v) \
         SELECT 't' || (g % $2::bigint), \
                now() - ((g % 1000000) || ' seconds')::interval, \
                (g % 100)::int \
         FROM generate_series(1, $1::bigint) g",
        &[&rows, &tenants],
    )
    .await
    .expect("seed");
    db::execute("ANALYZE bench_event", &[]).await.ok();

    let latest_sql = "SELECT id FROM bench_event WHERE tenant = 't7' \
                      ORDER BY created_at DESC LIMIT 20";

    // Before the index: a sequential scan + sort of the whole table.
    let scan_avg = time_text(latest_sql, 10).await;

    db::execute(
        "CREATE INDEX bench_event_tenant_created_at_idx ON bench_event (tenant, created_at)",
        &[],
    )
    .await
    .expect("index");
    db::execute("ANALYZE bench_event", &[]).await.ok();

    // After the index: a seek to the tenant's slice, already ordered.
    let seek_avg = time_text(latest_sql, 10).await;

    println!(
        "scale bench @ {rows} rows / {tenants} tenants — tenant-latest scan avg = {scan_avg:?}, \
         composite-index seek avg = {seek_avg:?}"
    );
    println!(
        "BENCH scenario=composite_index_tenant_latest rows={rows} tenants={tenants} \
         scan_us={} seek_us={}",
        scan_avg.as_micros(),
        seek_avg.as_micros()
    );

    // The regression signal: the composite index must make the query faster than
    // the scan. At scale it is dramatically faster; the non-strict compare keeps
    // CI non-flaky at tiny row counts while catching an index that stopped being
    // used.
    assert!(
        seek_avg <= scan_avg,
        "the composite-index seek ({seek_avg:?}) should beat the scan ({scan_avg:?}) at {rows} rows"
    );
}

/// Time a parameter-less query, averaged over `iters`.
async fn time_text(sql: &str, iters: u32) -> Duration {
    let mut total = Duration::ZERO;
    for _ in 0..iters {
        let start = Instant::now();
        db::sql(sql, &[]).await.expect("query");
        total += start.elapsed();
    }
    total / iters
}
