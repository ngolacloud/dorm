//! A reproducible scale benchmark against a real PostgreSQL (ADR 0036 / L16).
//!
//! Measures the two pagination shapes L4 (ADR 0024) generates — a keyset seek vs
//! a deep `OFFSET` — at a configurable row count (`DORM_BENCH_ROWS`, default
//! 50_000; set it to 10_000_000 on a dedicated bench host). The keyset query
//! seeks on the index; the `OFFSET` scans and discards, so its cost grows with
//! depth. The assertion is the regression signal; the printed numbers are the
//! measurement that an ADR records and a CI gate compares against a baseline.
//!
//! ```text
//! DORM_BENCH_ROWS=200000 DELONIX_ORM_TEST_DSN='host=127.0.0.1 port=5432 user=orm dbname=ormtest' \
//!   cargo test -p dorm-core --test scale_bench_live -- --ignored --nocapture
//! ```

use std::time::{Duration, Instant};

use dorm_core::db;
use dorm_core::value::Value;

fn dsn() -> Option<String> {
    std::env::var("DELONIX_ORM_TEST_DSN")
        .ok()
        .filter(|s| !s.trim().is_empty())
}

async fn time_query(sql: &str, boundary: i64, iters: u32) -> Duration {
    let mut total = Duration::ZERO;
    for _ in 0..iters {
        let start = Instant::now();
        db::sql(sql, &[Value::I64(boundary)]).await.expect("query");
        total += start.elapsed();
    }
    total / iters
}

#[tokio::test(flavor = "multi_thread")]
#[ignore = "needs a Postgres (DELONIX_ORM_TEST_DSN)"]
async fn keyset_pagination_beats_a_deep_offset_at_scale() {
    let Some(dsn) = dsn() else {
        eprintln!("skipped: DELONIX_ORM_TEST_DSN is not set");
        return;
    };
    std::env::set_var(dorm_core::db::DSN_ENV, &dsn);

    let rows: i64 = std::env::var("DORM_BENCH_ROWS")
        .ok()
        .and_then(|s| s.parse().ok())
        .unwrap_or(50_000);

    db::execute("DROP TABLE IF EXISTS bench_metric", &[])
        .await
        .expect("clean");
    db::execute(
        "CREATE TABLE bench_metric (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v INT NOT NULL)",
        &[],
    )
    .await
    .expect("table");
    // One fast seed.
    db::execute(
        "INSERT INTO bench_metric (v) SELECT (g % 100)::int FROM generate_series(1, $1::bigint) g",
        &[&rows],
    )
    .await
    .expect("seed");
    db::execute("ANALYZE bench_metric", &[]).await.ok();

    // A deep page, near the end: OFFSET must scan ~rows-10 rows and discard them;
    // keyset seeks straight to the boundary on the primary-key index.
    let deep = rows - 10;
    let boundary: i64 = db::sql(
        "SELECT id FROM bench_metric ORDER BY id OFFSET $1 LIMIT 1",
        &[Value::I64(deep)],
    )
    .await
    .expect("boundary")[0]
        .try_get(0)
        .unwrap();

    let offset_avg = time_query(
        "SELECT id FROM bench_metric ORDER BY id OFFSET $1 LIMIT 10",
        deep,
        20,
    )
    .await;
    let keyset_avg = time_query(
        "SELECT id FROM bench_metric WHERE id > $1 ORDER BY id LIMIT 10",
        boundary,
        20,
    )
    .await;

    println!(
        "scale bench @ {rows} rows — deep OFFSET avg = {offset_avg:?}, keyset avg = {keyset_avg:?}"
    );

    // The regression signal: keyset must not be slower than a deep OFFSET. At
    // scale it is dramatically faster; the generous factor keeps CI non-flaky
    // while still catching a regression that made keyset scan.
    assert!(
        keyset_avg <= offset_avg,
        "keyset ({keyset_avg:?}) should beat a deep OFFSET ({offset_avg:?}) at {rows} rows"
    );
}
