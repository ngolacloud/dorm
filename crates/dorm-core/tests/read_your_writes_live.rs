//! Read-your-writes LSN primitives against a real PostgreSQL (ADR 0030 / L8).
//!
//! The full lag-aware routing and `pg_wal_replay_pause()` proof need a streaming
//! replica (deferred, ADR 0030). What is proven here, on a single instance, is the
//! heart of the mechanism: the token advances monotonically across writes (so a
//! read can compare its token to a replica's replay position), the replay-lag and
//! caught-up checks run and report the primary's state correctly.
//!
//! ```text
//! DELONIX_ORM_TEST_DSN='host=127.0.0.1 port=5432 user=orm dbname=ormtest' \
//!   cargo test -p dorm-core --test read_your_writes_live -- --ignored --nocapture
//! ```

use dorm_core::db;

fn dsn() -> Option<String> {
    std::env::var("DELONIX_ORM_TEST_DSN")
        .ok()
        .filter(|s| !s.trim().is_empty())
}

#[tokio::test(flavor = "multi_thread")]
#[ignore = "needs a Postgres (DELONIX_ORM_TEST_DSN)"]
async fn the_write_lsn_token_advances_and_the_replica_checks_report_the_primary() {
    let Some(dsn) = dsn() else {
        eprintln!("skipped: DELONIX_ORM_TEST_DSN is not set");
        return;
    };
    std::env::set_var(dorm_core::db::DSN_ENV, &dsn);

    db::execute(
        "CREATE TABLE IF NOT EXISTS ryw_probe (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n INT)",
        &[],
    )
    .await
    .expect("probe table");

    // A token before a write, a write, then a token after it: the token advances.
    let before = db::write_lsn().await.expect("lsn before");
    db::execute("INSERT INTO ryw_probe (n) VALUES (1)", &[])
        .await
        .expect("a write");
    let after = db::write_lsn().await.expect("lsn after");

    // Compare the two LSNs server-side (pg_lsn ordering), the comparison a
    // read-your-writes read makes between its token and a replica's position.
    let advanced = db::sql(
        "SELECT (($2 || '')::pg_lsn > ($1 || '')::pg_lsn)",
        &[
            dorm_core::value::Value::Text(before.clone()),
            dorm_core::value::Value::Text(after.clone()),
        ],
    )
    .await
    .expect("compare")[0]
        .try_get::<bool>(0)
        .unwrap();
    assert!(advanced, "the write advanced the LSN: {before} -> {after}");

    // On the primary, `replica_caught_up` is false (there is no replay LSN) — the
    // signal to route such a read to the primary, which has its own writes.
    assert!(
        !db::replica_caught_up(&after).await.expect("caught_up"),
        "a primary reports not-caught-up (its replay LSN is NULL)"
    );

    // And the lag measurement is `None` on a primary (not a streaming standby).
    assert_eq!(
        db::replica_lag_seconds().await.expect("lag"),
        None,
        "a primary has no replication lag to report"
    );
}
